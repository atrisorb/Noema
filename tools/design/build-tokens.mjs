#!/usr/bin/env node
// tokens.json is canonical. This emits tokens.css and fails on drift with --check.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const tokensPath = fileURLToPath(new URL('../../crates/app/ui/src/design/tokens.json', import.meta.url));
const cssPath = fileURLToPath(new URL('../../crates/app/ui/src/design/tokens.css', import.meta.url));
const tokens = JSON.parse(readFileSync(tokensPath, 'utf8'));
const check = process.argv.includes('--check');
const fail = (message) => { console.error(`build-tokens: ${message}`); process.exit(1); };

if (tokens.schema !== 'noema.design-tokens/1') fail(`unexpected schema ${tokens.schema}`);
const cavity = tokens.themes?.cavity;
const bone = tokens.themes?.bone;
if (!cavity || !bone) fail('themes.cavity and themes.bone are required');
const colorKeys = Object.keys(cavity.color);
if (colorKeys.join('\0') !== Object.keys(bone.color).join('\0')) fail('theme color keys differ');
const shadowKeys = Object.keys(cavity.shadow);
if (shadowKeys.join('\0') !== Object.keys(bone.shadow).join('\0')) fail('theme shadow keys differ');
for (const group of ['font', 'type', 'space', 'radius', 'z', 'motion', 'ease', 'blur', 'glass', 'focus', 'chart']) {
  if (!tokens.shared?.[group]) fail(`shared.${group} is required`);
}

const lines = [];
const decl = (name, value) => `  --noema-${name}: ${value};`;
lines.push('/* Generated by tools/design/build-tokens.mjs from tokens.json. Do not edit. */');
lines.push(`/* ${tokens.name} ${tokens.designSystem} - ${tokens.updated} */`);
lines.push('');
lines.push(':root {');
lines.push('  color-scheme: dark;');
for (const [key, value] of Object.entries(tokens.shared.font)) lines.push(decl(`font-${key}`, value));
for (const [key, value] of Object.entries(tokens.shared.type)) {
  lines.push(decl(key, value.size));
  lines.push(decl(`leading-${key}`, value.line));
  lines.push(decl(`weight-${key}`, value.weight));
}
for (const [key, value] of Object.entries(tokens.shared.space)) lines.push(decl(`space-${key}`, value));
for (const [key, value] of Object.entries(tokens.shared.radius)) lines.push(decl(`radius-${key}`, value));
for (const [key, value] of Object.entries(tokens.shared.z)) lines.push(decl(`z-${key}`, value));
for (const [key, value] of Object.entries(tokens.shared.motion)) lines.push(decl(`motion-${key}`, value));
for (const [key, value] of Object.entries(tokens.shared.ease)) lines.push(decl(`ease-${key}`, value));
for (const [key, value] of Object.entries(tokens.shared.blur)) lines.push(decl(`blur-${key}`, value));
lines.push(decl('glass-saturate', tokens.shared.glass.saturate));
lines.push(decl('focus-width', tokens.shared.focus.width));
lines.push(decl('focus-offset', tokens.shared.focus.offset));
lines.push(decl('focus-color', 'var(--noema-nerve)'));
for (const [key, value] of Object.entries(cavity.color)) lines.push(decl(key, value));
for (const [key, value] of Object.entries(cavity.shadow)) lines.push(decl(`shadow-${key}`, value));
for (const [key, value] of Object.entries(tokens.shared.chart)) lines.push(decl(`chart-${key}`, `var(--noema-${value})`));
lines.push('}');
lines.push('');
lines.push('[data-theme="bone"] {');
lines.push('  color-scheme: light;');
for (const [key, value] of Object.entries(bone.color)) lines.push(decl(key, value));
for (const [key, value] of Object.entries(bone.shadow)) lines.push(decl(`shadow-${key}`, value));
lines.push('}');
lines.push('');
const css = lines.join('\n');

let current = '';
try { current = readFileSync(cssPath, 'utf8'); } catch { /* missing is a check failure */ }
if (check) {
  if (current !== css) fail('tokens.css is stale; run node tools/design/build-tokens.mjs');
  console.log(`tokens.css ok: ${colorKeys.length} color pairs, ${Object.keys(tokens.shared.type).length} type scales`);
  process.exit(0);
}
writeFileSync(cssPath, css);
console.log(`wrote ${cssPath}`);
